import { chromium } from "playwright";
const base="https://opctoai.com", SPACE="10000000-0000-0000-0000-000000000001";
const b=await chromium.launch();
const ctx=await b.newContext({viewport:{width:1440,height:900}});
await ctx.addCookies([{name:"instant_session",value:"qa-token-fullstack-1",domain:"opctoai.com",path:"/"}]);
const p=await ctx.newPage();
const errors=[]; p.on("console",m=>{if(m.type()==="error")errors.push(m.text());});
await p.goto(`${base}/inspace/spaces/${SPACE}/chat`,{waitUntil:"networkidle"}).catch(()=>{});
await p.waitForTimeout(3500);
const before = await p.locator(".chat-message").count();
const disabledBefore = await p.locator(".chat-send").isDisabled();
const msg = `QA ${Date.now()}`;
await p.locator("[data-chat-input]").fill(msg);
await p.waitForTimeout(400);
const disabledAfter = await p.locator(".chat-send").isDisabled();
await p.locator("[data-chat-input]").press("Enter");
await p.waitForTimeout(2500);
const after = await p.locator(".chat-message").count();
const found = await p.locator(".chat-message-text", {hasText: msg}).count();
await p.screenshot({path:"output/playwright/chat-sent.png"});
console.log(JSON.stringify({before, after, found, disabledBefore, disabledAfter, status: await p.locator("[data-realtime-status]").getAttribute("data-realtime-status"), errors:errors.slice(0,3)},null,1));
await b.close();
